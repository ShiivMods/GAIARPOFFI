import assert from "node:assert/strict";
import {test} from "node:test";
import {setupIsolatedLocalDb} from "./local-fixture.ts";
import {withLocalDb} from "../src/server/db/local.ts";
import {getCombatView,submitCombatCommand,resetCombat} from "../src/server/combat/local-repository.ts";
import {getExperienceView,getGmExperience,postCombatMessage,adjudicateCombat,decideSurrender} from "../src/server/combat/experience-repository.ts";
setupIsolatedLocalDb();
test("persistent RP, scanner, manual turn resolution and surrender archive",async()=>{
  const ids=Object.fromEntries(withLocalDb(db=>db.prepare("SELECT username,id FROM app_accounts").all()).map(r=>[String(r.username),String(r.id)]));
  const [a,b,c,gm,admin]=["joueur_01","joueur_02","joueur_03","maitre_du_jeu","administrateur"].map(k=>ids[k]);
  const id="starlight";
  await postCombatMessage(id,a,"Passerelle","Ordre privé");
  await postCombatMessage(id,a,"Canal externe","Signal public");
  assert.equal((await getExperienceView(id,c))?.experience.messages.length,1);
  assert.equal((await getExperienceView(id,b))?.experience.messages.length,2);
  assert.equal((await getExperienceView(id,c))?.experience.ships.find(s=>s.id==="raviolo")?.systems,null);
  assert.equal(await getExperienceView(id,admin),null);
  await assert.rejects(postCombatMessage(id,admin,"","test"),/Forbidden/);
  for(const [actor,orders] of [[a,["shield-boost","scan"]],[b,["fire"]],[c,["fire"]]] as const){
    let v=await getCombatView(id,actor);assert.ok(v);
    await submitCombatCommand(id,actor,v.revision,{kind:"orders",orders});
    v=await getCombatView(id,actor);assert.ok(v);
    await submitCombatCommand(id,actor,v.revision,{kind:"ready"});
  }
  const before=await getCombatView(id,a);assert.ok(before);
  const damage={raviolo:{damage:100,repair:50},k17:{damage:4300,repair:0}};
  await assert.rejects(adjudicateCombat(id,admin,before.revision,damage),/Forbidden/);
  assert.equal((await getGmExperience(id,gm))?.orders.length,3);
  await adjudicateCombat(id,gm,before.revision,damage);
  const after=await getExperienceView(id,a);assert.ok(after);
  assert.equal(after.turn,2);
  assert.equal(after.experience.ships.find(s=>s.id==="raviolo")?.shield.current,4900);
  assert.equal(after.experience.ships.find(s=>s.id==="k17")?.armor.current,2700);
  assert.equal(after.experience.ships.find(s=>s.id==="k17")?.estimatedSpeed,135);
  assert.equal(after.experience.history.length,1);
  assert.equal(after.experience.history[0].messages.length,2);
  assert.equal((await getExperienceView(id,c))?.experience.history[0].messages.length,1);
  await assert.rejects(adjudicateCombat(id,gm,before.revision,damage),/Stale revision/);
  await submitCombatCommand(id,c,after.revision,{kind:"surrender"});
  const pending=await getCombatView(id,a);assert.ok(pending);
  await assert.rejects(decideSurrender(id,b,pending.revision,true),/Forbidden/);
  await decideSurrender(id,a,pending.revision,false);
  const resumed=await getCombatView(id,c);assert.ok(resumed);
  await submitCombatCommand(id,c,resumed.revision,{kind:"surrender"});
  const again=await getCombatView(id,a);assert.ok(again);
  await decideSurrender(id,a,again.revision,true);
  const finished=await getExperienceView(id,a);assert.ok(finished);
  assert.match(finished.experience.result??"",/reddition/);
  assert.equal(finished.experience.history.length,2);
  await assert.rejects(submitCombatCommand(id,a,finished.revision,{kind:"orders",orders:["fire"]}),/Combat finished/);
  await resetCombat(id,gm,finished.revision);
  const reset=await getExperienceView(id,a);assert.ok(reset);
  assert.equal(reset.experience.result,null);
  assert.equal(reset.experience.history.length,0);
  assert.equal(reset.experience.ships.find(s=>s.id==="raviolo")?.shield.current,4950);
});
