import assert from "node:assert/strict";
import {test} from "node:test";
import {setupIsolatedLocalDb} from "./local-fixture.ts";
import {startRegistration,completeRegistration,getRegisteredCharacter} from "../src/server/auth/registration.ts";
import {withLocalDb} from "../src/server/db/local.ts";
import {listStudents,validateGraduation} from "../src/server/characters/education.ts";
import {educationProgressionRate,acquiredSpecialization} from "../src/game/characters/education.ts";
setupIsolatedLocalDb();
const input={dynasty:"Educia",firstName:"Ada",species:"Humain",sex:"Femme",faction:"Humanis",height:"170",weight:"65",age:"17",academy:"Sciences",history:"",traits:""};
test("education status survives aging; graduation requires an eligible student, GM and RP reference",()=>{
  const player=completeRegistration(startRegistration("student@example.test","test-local-uniquement"),input).account;
  const student=getRegisteredCharacter(player.id)!;
  const gm=withLocalDb(db=>String(db.prepare("SELECT id FROM app_accounts WHERE role='gm'").get()?.id));
  const admin=withLocalDb(db=>String(db.prepare("SELECT id FROM app_accounts WHERE role='admin'").get()?.id));
  assert.equal(student.educationStatus,"student");
  assert.equal(educationProgressionRate(17,"student"),0.25);
  assert.equal(educationProgressionRate(13,"none"),0);
  assert.equal(acquiredSpecialization("Sciences","student"),null);
  assert.throws(()=>listStudents(player.id),/Forbidden/);
  assert.throws(()=>validateGraduation(gm,student.id,"RP test"),/Graduation age/);
  withLocalDb(db=>db.prepare("UPDATE app_characters SET age=18 WHERE id=?").run(student.id));
  assert.equal(getRegisteredCharacter(player.id)?.educationStatus,"student");
  assert.equal(educationProgressionRate(18,"student"),0.25);
  assert.equal(listStudents(gm).length,1);
  assert.throws(()=>validateGraduation(player.id,student.id,"RP test"),/Forbidden/);
  assert.throws(()=>validateGraduation(admin,student.id,"RP test"),/Forbidden/);
  assert.throws(()=>validateGraduation(gm,student.id," "),/RP reference/);
  validateGraduation(gm,student.id,"RP de diplôme test");
  assert.equal(getRegisteredCharacter(player.id)?.educationStatus,"graduate");
  assert.equal(educationProgressionRate(18,"graduate"),1);
  assert.equal(acquiredSpecialization("Sciences","graduate"),"Scientifique");
  assert.equal(listStudents(gm).length,0);
  assert.throws(()=>validateGraduation(gm,student.id,"RP test"),/Not a student/);
  assert.equal(withLocalDb(db=>db.prepare("SELECT gm_account_id FROM academy_graduations WHERE character_id=?").get(student.id)?.gm_account_id),gm);
  const adult=completeRegistration(startRegistration("adult@example.test","test-local-uniquement"),{...input,dynasty:"Educor",age:"21",academy:"Politique"}).account;
  assert.equal(getRegisteredCharacter(adult.id)?.educationStatus,"graduate");
});
